/* =========================================================
   MODAL HELPERS
========================================================= */

function openModal(modal) {

    modal.classList.add("open");

    modal.setAttribute(
        "aria-hidden",
        "false"
    );

    document.body.style.overflow =
        "hidden";
}


function closeModal(modal) {

    modal.classList.remove("open");

    modal.setAttribute(
        "aria-hidden",
        "true"
    );

    if (
        !document.querySelector(".modal.open")
    ) {

        document.body.style.overflow =
            "";

    }
}



